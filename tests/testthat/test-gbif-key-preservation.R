test_that("GBIF cache keys retain the existing scalar and character contract", {
  samples <- c("bird name", " . / ", "A.b-c_d", "Abies Sp\u00e9cies", NA_character_)
  expected <- vapply(samples, function(x) gsub("[^A-Za-z0-9_-]", "_", x), character(1))
  actual <- vapply(samples, .gbif_cache_key, character(1))
  expect_identical(actual, expected)
  expect_identical(.gbif_cache_key("A.b"), "A_b")
  expect_identical(.gbif_cache_key(NA_character_), NA_character_)
  expect_error(.gbif_cache_key(""))
  expect_error(.gbif_cache_key(character()))
  expect_error(.gbif_cache_key(c("a", "b")))
  expect_error(.gbif_cache_key(1))
})

test_that("GBIF and WorldClim retain offline cache lookup for the same species", {
  root <- tempfile("gbif-cache-"); dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  gbif <- file.path(root, "gbif"); dir.create(gbif)
  extracts <- file.path(root, "extracts"); dir.create(extracts)
  species <- "Abies Sp\u00e9cies.1"
  key <- gsub("[^A-Za-z0-9_-]", "_", species)
  cached <- list(species = species, centroid_lat = NA_real_, centroid_lon = NA_real_,
                 n_occurrences = 0L)
  saveRDS(cached, file.path(gbif, paste0(key, ".rds")))
  found <- pull_gbif_centroids(species, cache_dir = gbif, verbose = FALSE)
  expect_identical(found$species, species)
  expect_equal(found$n_occurrences, 0L)
  expect_true(is.na(found$centroid_lat))
  climate <- .wc_extract_one(species, gbif_cache_dir = gbif, wc_extracts_dir = extracts)
  expect_identical(climate$species, species)
  expect_identical(climate$n_extracted, 0L)
  expect_true(all(is.na(climate$bio_median)))
  saved <- readRDS(file.path(extracts, paste0(.wc_cache_key(species), ".rds")))
  expect_identical(saved$reason, "no_gbif_points")
  expect_identical(readRDS(file.path(gbif, paste0(key, ".rds"))), cached)
})
