source("script/validation_20261018/summarise.R")
jobs <- data.frame(job_id=paste0("p",1:3),scenario_id="s",rep=1:3,seed=1:3,adapter="posterior")
metric <- function(n,cov,width) data.frame(trait="x",n=n,n_expected=n,n_finite_scored=n,n_missing_or_nonfinite=0L,coverage=cov,mean_width=width,status="ok")
rec <- function(i,m) list(job_id=paste0("p",i),status="ok",metrics=list(posterior_converged=TRUE,posterior_cell_interval=m))
x <- validation_posterior_interval_tables(list(rec(1,metric(10,.8,2)),rec(2,metric(100,1,4))),jobs)
stopifnot(x$summary$nrep==2,x$summary$nrep_missing==1,abs(x$summary$mean_coverage-.9)<1e-12,abs(x$summary$mcse_coverage-.1)<1e-12)
legacy <- data.frame(trait="x",n=10,coverage=1,mean_width=2)
x <- validation_posterior_interval_tables(list(rec(1,legacy)),jobs)
stopifnot(x$summary$nrep==0,x$by_replicate$interval_status[1]=="unavailable")
lost <- metric(10,1,2);lost$n_finite_scored<-9L;lost$n_missing_or_nonfinite<-1L;lost$status<-"failed"
x <- validation_posterior_interval_tables(list(rec(1,lost)),jobs)
stopifnot(x$summary$nrep==0,x$by_replicate$interval_status[1]=="failed")
stopifnot(nrow(validation_posterior_interval_tables(list(),transform(jobs,adapter="prediction"))$summary)==0L)
cat("SUMMARY_PASS\n")
