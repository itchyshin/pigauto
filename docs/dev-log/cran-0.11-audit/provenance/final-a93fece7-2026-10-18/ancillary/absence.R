args <- commandArgs(TRUE)
root <- normalizePath(args[1],mustWork=TRUE)
lib <- normalizePath(file.path(root,"absence-library"),mustWork=TRUE)
stopifnot(identical(Sys.getenv("NOT_CRAN",unset=NA_character_),NA_character_))
stopifnot(identical(normalizePath(.libPaths()[1]),lib),all(normalizePath(.libPaths()) %in% normalizePath(c(lib,.Library))))
library(pigauto);library(testthat)
torch::torch_set_num_threads(1L)
set.seed(20261018L)
stopifnot(identical(normalizePath(find.package("pigauto")),normalizePath(file.path(lib,"pigauto"))))
stopifnot(!requireNamespace("rgbif",quietly=TRUE),!requireNamespace("terra",quietly=TRUE))
writeLines(capture.output(list(paths=.libPaths(),pigauto=find.package("pigauto"),version=packageVersion("pigauto"),rgbif=FALSE,terra=FALSE,session=sessionInfo())),file.path(root,"absence-session.txt"))
files <- c("test-gbif-centroids.R","test-worldclim-covariates.R")
checkroot <- file.path(root,"absence.Rcheck");dir.create(file.path(checkroot,"tests","testthat"),recursive=TRUE)
for (f in files) stopifnot(file.copy(file.path(root,"exact-source","pigauto","tests","testthat",f),file.path(checkroot,"tests","testthat",f)))
stopifnot(!file.exists(file.path(checkroot,"DESCRIPTION")))
setwd(file.path(checkroot,"tests"));options(useFancyQuotes=FALSE)
rep <- testthat::CheckReporter$new()
results <- lapply(files,function(f)testthat::test_file(file.path("testthat",f),package="pigauto",reporter=rep))
saveRDS(list(results=results,warnings=rep$warnings$as_list(),skips=rep$skips$as_list(),problems=rep$problems$as_list()),file.path(root,"absence-results.rds"))
writeLines(capture.output(lapply(rep$skips$as_list(),function(x)str(x,max.level=1))),file.path(root,"absence-skips.txt"))
writeLines(capture.output(lapply(rep$warnings$as_list(),function(x)str(x,max.level=1))),file.path(root,"absence-warnings.txt"))
jsonlite::write_json(list(pass=rep$n_ok,fail=rep$problems$size(),warn=rep$warnings$size(),skip=rep$skips$size(),files=files,not_cran="UNSET",rgbif=FALSE,terra=FALSE),file.path(root,"absence-summary.json"),auto_unbox=TRUE,pretty=TRUE)
stopifnot(rep$problems$size()==0L,rep$warnings$size()==0L)
cat("FINAL_EXACT_OPTIONAL_ABSENCE_BRANCHES_PASS\n")
